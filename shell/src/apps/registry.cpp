// The apps on this device: the ones built into ZeroShell (listed in
// shell/apps.cmake) plus every installed app module (docs/APPS.md).
//
// A module is /usr/lib/zeroos/apps/<name>.so, holding one app or several (ZS_APP_DIR overrides the folder).
// It is loaded once and never unloaded: an open app's code must stay mapped,
// and dlopen() of a path that is already loaded returns the old copy. So an
// upgraded module only takes effect after ZeroShell restarts; the Apps store
// does that (app_modules_stale()).
#include <dirent.h>
#include <dlfcn.h>
#include <sys/stat.h>

#include <algorithm>
#include <cstdio>
#include <cstdlib>
#include <map>

#include "ui/app.h"
#include "ui/theme.h"

namespace zs {

// Generated by ZeroShellApps.cmake: the apps compiled into this binary.
void zs_builtin_apps(std::vector<AppInfo>& out);

namespace {

struct Loaded {
    const AppModule* mod = nullptr;
    struct timespec mtime{};   // of the file when it was loaded
    std::string error;         // why it couldn't be loaded ("" = loaded)
    bool opened = false;       // dlopen() worked (so it can't be loaded again)
};

std::vector<AppInfo> g_apps;
std::map<std::string, Loaded> g_modules;   // by path
bool g_loaded = false;

std::string module_dir() {
    const char* d = std::getenv("ZS_APP_DIR");
    return d && *d ? d : "/usr/lib/zeroos/apps";
}

bool same_time(const struct timespec& a, const struct timespec& b) {
    return a.tv_sec == b.tv_sec && a.tv_nsec == b.tv_nsec;
}

const AppModule* load(const std::string& path, const struct stat& st) {
    auto it = g_modules.find(path);
    if (it != g_modules.end()) {
        // Loaded before, or failed. A file dlopen() refused may have been
        // fixed since (a new version installed): then try it again.
        if (it->second.opened || same_time(it->second.mtime, st.st_mtim)) return it->second.mod;
        g_modules.erase(it);
    }
    Loaded& l = g_modules[path];
    l.mtime = st.st_mtim;
    // RTLD_NOW: a module that needs something this ZeroShell lacks fails
    // here, not with a crash when the app is opened.
    void* h = dlopen(path.c_str(), RTLD_NOW | RTLD_LOCAL);
    if (!h) {
        l.error = dlerror();
        std::fprintf(stderr, "zeroshell: app module %s: %s\n", path.c_str(), l.error.c_str());
        return nullptr;
    }
    l.opened = true;
    using Fn = const AppModule* (*)();
    auto fn = reinterpret_cast<Fn>(dlsym(h, "zs_app_module"));
    const AppModule* m = fn ? fn() : nullptr;
    if (!m || !m->id) {
        l.error = "not a ZeroShell app (no zs_app_module)";
        m = nullptr;
    }
    for (const AppModule* a = m; a && a->id; ++a) {
        if (a->abi != ZS_APP_ABI) {
            l.error = "built for app ABI " + std::to_string(a->abi) + ", this ZeroShell has " + std::to_string(ZS_APP_ABI);
            m = nullptr;
        } else if (!a->name || !a->symbol || !a->make) {
            l.error = "incomplete zs_app_module";
            m = nullptr;
        }
    }
    if (!m) {
        std::fprintf(stderr, "zeroshell: app module %s: %s\n", path.c_str(), l.error.c_str());
        return nullptr;   // the handle stays open; it's harmless and tiny
    }
    l.mod = m;
    for (const AppModule* a = m; a->id; ++a)
        std::fprintf(stderr, "zeroshell: loaded app %s from %s\n", a->id, path.c_str());
    return m;
}

void scan() {
    g_apps.clear();
    zs_builtin_apps(g_apps);
    std::string dir = module_dir();
    if (DIR* d = opendir(dir.c_str())) {
        std::vector<std::string> names;
        while (dirent* e = readdir(d)) {
            std::string n = e->d_name;
            if (n.size() > 3 && n.compare(n.size() - 3, 3, ".so") == 0) names.push_back(n);
        }
        closedir(d);
        std::sort(names.begin(), names.end());
        for (auto& n : names) {
            std::string path = dir + "/" + n;
            struct stat st{};
            if (stat(path.c_str(), &st) != 0 || !S_ISREG(st.st_mode)) continue;
            const AppModule* m = load(path, st);
            for (; m && m->id; ++m) {
                bool taken = false;   // a built-in app (or one loaded already) wins
                for (auto& a : g_apps) taken = taken || a.id == m->id;
                if (taken) continue;
                AppInfo info{m->id, m->name, m->symbol, m->color, m->make};
                info.order = m->order;
                info.builtin = false;
                g_apps.push_back(std::move(info));
            }
        }
    }
    std::stable_sort(g_apps.begin(), g_apps.end(), [](const AppInfo& a, const AppInfo& b) {
        return a.order != b.order ? a.order < b.order : a.name < b.name;
    });
    g_loaded = true;
}

}  // namespace

const std::vector<AppInfo>& app_registry() {
    if (!g_loaded) scan();
    return g_apps;
}

void app_registry_reload() { scan(); }

const AppInfo* app_find(const std::string& id) {
    for (auto& a : app_registry())
        if (a.id == id) return &a;
    return nullptr;
}

bool app_modules_stale() {
    for (auto& [path, l] : g_modules) {
        if (!l.mod) continue;
        struct stat st{};
        // Gone (removed) is fine: the code stays mapped until we exit.
        if (stat(path.c_str(), &st) == 0 && !same_time(st.st_mtim, l.mtime)) return true;
    }
    return false;
}

}  // namespace zs

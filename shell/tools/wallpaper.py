#!/usr/bin/env python3
"""Regenerate shell/src/ui/wallpaper_data.cpp: the photographs behind home
and the lock screen.

    python3 shell/tools/wallpaper.py [--preview out.png] [--src photo.jpg --home-y F [--write]]

Needs Pillow. The output is committed (like the fonts), so a build needs
nothing but a compiler. Steps:

1. Crop the source photograph (shell/tools/wallpapers/) for each target and
   scale it to the whole screen, 320 x 170, in greyscale.
2. Bake in the scrim: darker where text sits on it (the status bar, home's
   search box and pins' names, Recent on the left and the clock on the right,
   the lock screen's clock). Nothing is blended on the device.
3. Dither to 32 neutral greys with a 4 x 4 ordered dither. RGB565 has 5 bits
   of red and blue but 6 of green, so finer greys would tint green or
   magenta; 32 levels with the same value in every channel stay neutral and
   the dither hides the steps.
4. Write an LVGL RGB565 image (little-endian, as the display buffer is).
"""
import argparse
import os

from PIL import Image

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "..", "src", "ui", "wallpaper_data.cpp")
W, H = 320, 170          # the whole screen: the status bar sits on the photo
BAYER = [[0, 8, 2, 10], [12, 4, 14, 6], [3, 11, 1, 9], [15, 7, 13, 5]]


# Home's shading down the screen: (y, how much of the photo shows), joined
# by straight lines. Smooth, so no band shows where one area meets the next.
HOME_RAMP = [(0, 0.4), (20, 0.45), (46, 0.72), (66, 0.72), (96, 0.52), (170, 0.46)]


def ramp(points, v):
    for (a, ka), (b, kb) in zip(points, points[1:]):
        if v <= b:
            return ka + (kb - ka) * (v - a) / (b - a)
    return points[-1][1]


def home_scrim(x, y):
    """Home: how much of the photo shows at (x, y), 1 = all, 0 = black.

    The layout (ui/launcher.cpp): status bar 0-20, search box 23-45, pins
    47-83, then Recent on the left (to x 154) and the time and date on the
    right. White text everywhere, so the photo is dimmed throughout, a little
    more under the status bar, the search box and Recent, and never black.
    """
    keep = ramp(HOME_RAMP, y)
    if y > 80:                                   # Recent's names, on the left
        t = min(1.0, (y - 80) / 20) * max(0.0, min(1.0, (170 - x) / 60))
        keep *= 1 - 0.18 * t
    return keep


def lock_scrim(x, y):
    """Lock: darker on the left (the clock) and along the bottom (the hint)."""
    keep = 0.4 + 0.6 * min(1.0, x / 180)
    if y > 110:
        keep *= 1 - 0.7 * (y - 110) / 60
    if y < 20:
        keep *= 0.6
    return keep


# Each screen has its own photograph. Home takes the whole width, cut from
# HOME_Y (a fraction of the height left over: 0 is the top, so the river
# runs under the pins). The lock screen keeps the Tetons and its pixel box
# in the 1280 px wide source: the right part, the clock sits on the left.
HOME_SRC, HOME_Y = "firehole-river.jpg", 0.0
LOCK_SRC, LOCK_BOX = "tetons-snake-river.jpg", (380, 0, 1280, 478)


def crop_box(img, x0, width, y_frac):
    """A box `width` of the image wide from `x0` (fractions), screen-shaped."""
    w, h = img.size
    m = round(w * 0.015)                 # scans have a border: trim it
    w, h = w - 2 * m, h - 2 * m
    cw = int(w * width)
    ch = min(h, round(cw * H / W))
    left = m + int(w * x0)
    top = m + round((h - ch) * y_frac)
    return (left, top, left + cw, top + ch)


def build(img, box, scrim):
    img = img.convert("L").crop(box).resize((W, H), Image.LANCZOS)
    px = img.load()
    out = []
    for y in range(H):
        for x in range(W):
            v = px[x, y] * scrim(x, y) / 255 * 31          # 0..31 with fraction
            v5 = int(v + (BAYER[y % 4][x % 4] + 0.5) / 16)
            out.append(max(0, min(31, v5)))
    return out


def rgb565(v5):
    g6 = (v5 << 1) | (v5 >> 4)
    return (v5 << 11) | (g6 << 5) | v5


def write_cpp(images, credit):
    parts = []
    for name, levels in images:
        data = bytearray()
        for v in levels:
            p = rgb565(v)
            data += bytes((p & 0xFF, p >> 8))
        rows = "\n".join("    " + ",".join("0x%02x" % b for b in data[i:i + 24]) + ","
                         for i in range(0, len(data), 24))
        parts.append(f"""const uint8_t k_{name}[{len(data)}] = {{
{rows}
}};""")
    funcs = "\n\n".join(f"""const lv_image_dsc_t* wallpaper_{name}() {{
    static const lv_image_dsc_t dsc = make(k_{name}, sizeof k_{name});
    return &dsc;
}}""" for name, _ in images)
    body = "\n\n".join(parts)
    with open(OUT, "w") as f:
        f.write(f"""// Generated by shell/tools/wallpaper.py from shell/tools/wallpapers/
// {HOME_SRC} (home) and {LOCK_SRC} (lock screen). Do not edit.
//
{credit}
#include "ui/wallpaper.h"

namespace zs {{

namespace {{
{body}

lv_image_dsc_t make(const uint8_t* px, uint32_t size) {{
    lv_image_dsc_t d{{}};
    d.header.magic = LV_IMAGE_HEADER_MAGIC;
    d.header.cf = LV_COLOR_FORMAT_RGB565;
    d.header.w = {W};
    d.header.h = {H};
    d.header.stride = {W * 2};
    d.data_size = size;
    d.data = px;
    return d;
}}
}}  // namespace

{funcs}

}}  // namespace zs
""")


def preview(images, path):
    sheet = Image.new("L", (W * 2, H * 2 * len(images)))
    for i, (_, levels) in enumerate(images):
        img = Image.new("L", (W, H))
        img.putdata([round(v * 255 / 31) for v in levels])
        sheet.paste(img.resize((W * 2, H * 2), Image.NEAREST), (0, i * H * 2))
    sheet.save(path)


# For the generated file's header (and the README's credits).
CREDIT = """// Home: Ansel Adams, "Firehole River, Yellowstone National Park", Wyoming,
// ca. 1941-1942. U.S. National Archives, Records of the National Park
// Service, 79-AA-T14.
// Lock screen: Ansel Adams, "The Tetons and the Snake River", Grand Teton
// National Park, 1942. U.S. National Archives, Records of the National Park
// Service, 79-AA-G01.
// Both public domain (works of the U.S. government)."""


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("--preview", help="also save a 2x PNG of the results")
    ap.add_argument("--src", help="try another photograph on home (writes the .cpp only with --write)")
    ap.add_argument("--write", action="store_true")
    ap.add_argument("--home-y", type=float, default=HOME_Y)
    a = ap.parse_args()
    home = Image.open(a.src or os.path.join(HERE, "wallpapers", HOME_SRC))
    lock = Image.open(os.path.join(HERE, "wallpapers", LOCK_SRC))
    images = [
        ("home", build(home, crop_box(home, 0, 1, a.home_y), home_scrim)),
        ("lock", build(lock, LOCK_BOX, lock_scrim)),
    ]
    if not a.src or a.write:
        write_cpp(images, CREDIT)
        print("wrote", os.path.relpath(OUT))
    if a.preview:
        preview(images, a.preview)
